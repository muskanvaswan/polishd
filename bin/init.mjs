/**
 * `npx @polishd/next init` — scaffold the glue files a Next.js app needs to wire
 * up Polishd. Node builtins only; zero runtime dependencies.
 *
 * It writes no proxy: the ingest route mints the session cookie itself, so a
 * host's own `proxy.ts` / `middleware.ts` is never touched or merged into.
 *
 * Flags:
 *   --force     regenerate files this CLI wrote (backed up first). Files it did
 *               not write are never overwritten, with or without this flag.
 *   --dry-run   print what would happen, write nothing
 *   --js        emit .js/.jsx instead of TypeScript
 *   --config    also write a starter polishd.config.ts
 *   --fix-workflow[=api-key]
 *               also write the Fix workflow (.github/workflows/claude.yml),
 *               reading CLAUDE_CODE_OAUTH_TOKEN, or ANTHROPIC_API_KEY with =api-key
 *
 * It also writes polishd.defaults.json when there is none — the site's
 * description, audience, values, repository and model, committed so the
 * dashboard opens knowing them — and the page imports it. That file is the
 * owner's, so it is never overwritten, not even with --force.
 */
import { appendFileSync, copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";

import {
  CLAUDE_APP_INSTALL_URL,
  DEFAULTS_FILE,
  FIX_SECRET,
  FIX_WORKFLOW_PATH,
  c,
  detectCacheComponents,
  detectGithubRepo,
  detectLayout,
  detectNextMajor,
  gitRoot,
  githubTokenUrl,
  nextLoadsClientInstrumentation,
  nodeVersionOk,
  readText,
  recommendedWorkflow,
} from "./shared.mjs";

// Every generated file carries this marker. It is what lets `--force` tell "a
// file I wrote and may regenerate" apart from "the user's own code", which is
// the difference between a convenience flag and a data-loss bug.
const SENTINEL = "@polishd/next init";
const STAMP =
  `// Generated by \`npx ${SENTINEL}\`. Edit freely — \`--force\` backs up\n` +
  `// this file before regenerating it.\n`;

export function runInit(argv, cwd) {
  const args = new Set(argv);
  const FORCE = args.has("--force");
  const DRY = args.has("--dry-run");
  const JS = args.has("--js");
  const WANT_CONFIG = args.has("--config");
  const fixFlag = argv.find((a) => a === "--fix-workflow" || a.startsWith("--fix-workflow="));
  const fixSecret = fixFlag?.includes("=") ? fixFlag.split("=")[1] : "oauth-token";
  if (fixFlag && !FIX_SECRET[fixSecret]) {
    console.error(c.warn(`✗ --fix-workflow takes =api-key, or nothing for the subscription token.`));
    return 1;
  }
  const codeExt = JS ? "js" : "ts";
  const pageExt = JS ? "jsx" : "tsx";

  // ── Detect project layout ──────────────────────────────────────────────────
  const layout = detectLayout(cwd);
  if (!layout.found) {
    console.error(
      c.warn("✗ Could not find an `app/` or `src/app/` directory.\n") +
        "  Run this from the root of a Next.js App Router project.",
    );
    return 1;
  }
  const { base, appDir } = layout;
  console.log(
    c.ok(`✔ Detected Next.js App Router`) +
      c.dim(` (${layout.hasSrcApp ? "src/ layout" : "root layout"})`),
  );

  // The dev store uses `node:sqlite`, which landed in 22.5.0. Checked here
  // rather than left to a confusing "cannot find module" at first request.
  if (!nodeVersionOk()) {
    console.log(
      c.warn(`⚠ Node ${process.versions.node}`) +
        c.dim(" — Polishd needs >= 22.5.0 (the dev store uses node:sqlite)."),
    );
  }

  // Capture starts from instrumentation-client.ts, which Next loads from 15.3.
  // Below that every file here is written and nothing is ever captured, so
  // say so now rather than leave it to an empty dashboard.
  const next = detectNextMajor(cwd);
  if (nextLoadsClientInstrumentation(next) === false) {
    console.log(
      c.warn(`⚠ Next.js ${next.version}`) +
        c.dim(" — Polishd needs >= 15.3, the first Next that loads instrumentation-client.ts.") +
        c.dim("\n  Below it capture never starts. Upgrade Next."),
    );
  }

  // Cache Components rejects `runtime` and `dynamic` in the route and the page,
  // and wants the dashboard's cookie reads inside <Suspense>.
  const cc = detectCacheComponents(cwd);
  if (cc.on) {
    console.log(
      c.ok(`✔ Detected cacheComponents`) +
        c.dim(` in ${cc.file} — writing the route and page without runtime/dynamic`),
    );
  }
  const ccNote =
    `// cacheComponents is on, so there is no \`runtime\` or \`dynamic\` here: Next\n` +
    `// rejects both. Node is already the runtime, and nothing here is cached.\n`;

  // The page imports the defaults file rather than the package reading it
  // from disk, so the bundler ships it on hosts whose functions can't see
  // the repo.
  const pageDir = join(appDir, "polishd");
  const defaultsImport = relative(pageDir, DEFAULTS_FILE).split(sep).join("/");
  const pageOpts = cc.on ? "{ defaults, suspense: true }" : "{ defaults }";

  // ── File templates ─────────────────────────────────────────────────────────
  const files = [
    {
      path: join(base, `instrumentation-client.${codeExt}`),
      body: `import { initPolishd } from "@polishd/next/client";\n\ninitPolishd();\n`,
    },
    {
      path: join(appDir, "api", "polishd", `route.${codeExt}`),
      // runtime/dynamic must be declared here, not re-exported: Next statically
      // parses route segment config and rejects `export { runtime } from ...`
      // ("Next.js can't recognize the exported `runtime` field in route").
      body:
        `import { createPolishdRoute } from "@polishd/next/route";\n\n` +
        (cc.on
          ? ccNote
          : `// node:sqlite / pg need the Node runtime — never the Edge runtime.\n` +
            `export const runtime = "nodejs";\n` +
            `// This route mutates per-request; it must never be statically cached.\n` +
            `export const dynamic = "force-dynamic";\n`) +
        `\nexport const POST = createPolishdRoute();\n`,
    },
    {
      path: join(pageDir, `page.${pageExt}`),
      body:
        `// The dashboard's own stylesheet. Self-contained and scoped to\n` +
        `// .polishd-root, so it needs no Tailwind in this app and cannot\n` +
        `// affect anything outside the dashboard.\n` +
        `import "@polishd/next/dashboard.css";\n` +
        `import { createPolishdPage } from "@polishd/next/dashboard";\n\n` +
        `// What the site is, its repository and its model: defaults the dashboard\n` +
        `// opens with, which anything saved in the dashboard overrides. Committed,\n` +
        `// so never put a key in it.\n` +
        `import defaults from "${defaultsImport}";\n\n` +
        `// The dashboard's metadata, which keeps /polishd out of search engines.\n` +
        `export { metadata } from "@polishd/next/dashboard";\n\n` +
        (cc.on
          ? ccNote + `\n`
          : `// Next requires these to be declared inline in the page module.\n` +
            `export const runtime = "nodejs";\n` +
            `export const dynamic = "force-dynamic";\n`) +
        `// Server actions inherit this page's time limit; 300s gives the AI\n` +
        `// analyses headroom on hosts with strict function limits.\n` +
        `export const maxDuration = 300;\n\n` +
        `// In production the dashboard refuses to render until you either set\n` +
        `// POLISHD_DASHBOARD_TOKEN, pass your own \`authenticate\`, or opt out\n` +
        `// explicitly with POLISHD_DASHBOARD_PUBLIC=true. It can change your AI\n` +
        `// settings and spend your model tokens, so it is not public by default.\n` +
        (cc.on
          ? `// \`suspense\` renders it inside <Suspense>, which Cache Components needs\n` +
            `// around the cookies it reads on every request.\n`
          : ``) +
        `export default createPolishdPage(${pageOpts});\n`,
    },
  ];

  if (WANT_CONFIG) {
    files.push({
      path: `polishd.config.${codeExt}`,
      body:
        `import { definePolishdConfig } from "@polishd/next";\n\n` +
        `// NOTE: nothing imports this for you. Pass it to initPolishd(),\n` +
        `// createPolishdRoute() and your proxy explicitly, or the layers will\n` +
        `// disagree. For the session cookie name prefer POLISHD_SESSION_COOKIE,\n` +
        `// which every runtime can read.\n` +
        `export default definePolishdConfig({\n` +
        `  // sampleRate: 1,\n` +
        `  // rageClick: { count: 3, windowMs: 500 },\n` +
        `});\n`,
    });
  }

  // The workflow lives at the repository root, which in a monorepo is above
  // the app.
  const fixPath = relative(cwd, join(gitRoot(cwd) ?? cwd, FIX_WORKFLOW_PATH));
  if (fixFlag) {
    files.push({
      path: fixPath,
      stamp:
        `# Generated by \`npx ${SENTINEL} --fix-workflow\` for Polishd's Fix button:\n` +
        `# the stock anthropics/claude-code-action workflow, with a turn cap.\n`,
      body: recommendedWorkflow(fixSecret),
    });
  }

  // ── Write ──────────────────────────────────────────────────────────────────
  /** Did this CLI write the file currently at `abs`? */
  const isOurs = (abs) => (readText(abs) ?? "").includes(SENTINEL);

  function write(file) {
    const abs = join(cwd, file.path);
    const body = (file.stamp ?? STAMP) + file.body;

    if (existsSync(abs)) {
      // Never overwrite code this CLI did not author — not even with --force.
      // Losing a hand-written proxy (auth redirects, i18n, rate limiting) to a
      // flag someone passed for an unrelated skipped file is not a tradeoff.
      if (!isOurs(abs)) {
        console.log(
          c.warn(`⚠ ${file.path} exists and was not written by Polishd`) +
            c.dim(" — left untouched.\n") +
            c.dim(`  Rename or delete it to have a fresh copy scaffolded.`),
        );
        return;
      }
      if (!FORCE) {
        console.log(
          c.dim(`• ${file.path} already scaffolded — skipped (use --force to regenerate)`),
        );
        return;
      }
      // Regenerating an untouched file would only leave a .bak identical to it.
      if (readText(abs) === body) {
        console.log(c.dim(`• ${file.path} already matches the current template — skipped`));
        return;
      }
      if (DRY) {
        console.log(c.dim(`• would back up ${file.path} → ${file.path}.bak and regenerate`));
        return;
      }
      copyFileSync(abs, `${abs}.bak`);
      writeFileSync(abs, body);
      console.log(
        c.ok(`✔ Regenerated ${file.path}`) + c.dim(` (previous copy saved as ${file.path}.bak)`),
      );
      return;
    }

    if (DRY) {
      console.log(c.dim(`• would write ${file.path}`));
      return;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
    console.log(c.ok(`✔ Created ${file.path}`));
  }

  for (const f of files) write(f);

  // The defaults file is data, and the owner's: JSON has no comment to mark
  // it as ours, and whatever is in it was put there on purpose. Written once.
  const repo = detectGithubRepo(cwd);
  const defaultsAbs = join(cwd, DEFAULTS_FILE);
  if (existsSync(defaultsAbs)) {
    console.log(c.dim(`• ${DEFAULTS_FILE} exists — kept as it is`));
  } else if (DRY) {
    console.log(c.dim(`• would write ${DEFAULTS_FILE}`));
  } else {
    const skeleton = {
      site: { description: "", audience: "", values: "" },
      github: { repo: repo ?? "" },
      ai: { provider: "", model: "", apiKeyEnv: "" },
    };
    writeFileSync(defaultsAbs, `${JSON.stringify(skeleton, null, 2)}\n`);
    console.log(
      c.ok(`✔ Created ${DEFAULTS_FILE}`) +
        c.dim(repo ? ` (repository ${repo} from the origin remote)` : ""),
    );
  }

  // A page from an earlier init, kept because --force wasn't passed, doesn't
  // import the file, so nothing in it would be read.
  const pageRel = join(pageDir, `page.${pageExt}`);
  const pageSrc = readText(join(cwd, pageRel));
  if (pageSrc && !pageSrc.includes(DEFAULTS_FILE)) {
    console.log(
      c.warn(`⚠ ${pageRel} doesn't import ${DEFAULTS_FILE}, so the dashboard won't read it.`) +
        (isOurs(join(cwd, pageRel))
          ? c.dim("\n  Re-run with --force to regenerate the page (it's backed up first).")
          : c.dim(
              `\n  Add \`import defaults from "${defaultsImport}";\` and pass it:` +
                ` \`createPolishdPage({ defaults, ...yourOptions })\`.`,
            )),
    );
  }

  // A proxy an earlier `init` wrote does nothing the route doesn't now. It's
  // harmless, so it's left alone; deleting it is the owner's call, since they
  // may have added their own logic to it since.
  for (const name of ["proxy", "middleware"]) {
    const rel = join(base, `${name}.${codeExt}`);
    if (isOurs(join(cwd, rel))) {
      console.log(
        c.dim(`• ${rel} from an earlier init is no longer needed`) +
          c.dim(" — the ingest route mints the session cookie now. Delete it unless you've") +
          c.dim(" added your own logic to it."),
      );
    }
  }

  // ── .gitignore ─────────────────────────────────────────────────────────────
  const giPath = join(cwd, ".gitignore");
  const gi = readText(giPath) ?? "";
  if (!gi.includes(".polishd")) {
    if (DRY) {
      console.log(c.dim("• would add .polishd/ to .gitignore"));
    } else {
      appendFileSync(giPath, `${gi.endsWith("\n") || gi === "" ? "" : "\n"}.polishd/\n`);
      console.log(c.ok("✔ Added .polishd/ to .gitignore"));
    }
  }

  const steps = [
    `Local dev needs nothing — events write to ${c.dim(".polishd/analytics.db")} (SQLite).`,
    `Fill in ${c.dim(DEFAULTS_FILE)}: what the site is, who it's for, what it values.`,
    `For production, set ${c.dim("POLISHD_DATABASE_URL")} (pooled Postgres). See DATABASE.md.`,
    `Set ${c.dim("POLISHD_DASHBOARD_TOKEN")} to protect ${c.bold("/polishd")} in production.`,
    `To file issues, create a GitHub token (the form opens filled in; pick the repo, Generate)` +
      ` and set it as ${c.dim("POLISHD_GITHUB_TOKEN")}:\n     ${githubTokenUrl(repo ?? undefined)}`,
  ];
  if (fixFlag) {
    steps.push(
      `For the Fix workflow, install the Claude GitHub App on the repo:\n     ${CLAUDE_APP_INSTALL_URL}`,
      fixSecret === "api-key"
        ? `Add the Actions secret ${c.dim("ANTHROPIC_API_KEY")}: ${c.dim("gh secret set ANTHROPIC_API_KEY")}`
        : `Run ${c.dim("claude setup-token")}, then add what it prints as an Actions secret:` +
            ` ${c.dim("gh secret set CLAUDE_CODE_OAUTH_TOKEN")}`,
    );
  }
  steps.push(
    `Visit ${c.bold("/polishd")} to see the dashboard.`,
    `Check the wiring with ${c.bold("npx @polishd/next doctor")}.`,
  );
  console.log(
    `\n${c.bold("Next steps:")}\n` +
      steps.map((s, i) => `  ${i + 1}. ${s}`).join("\n") +
      (DRY ? c.warn("\n\n(dry run — nothing was written)") : ""),
  );

  return 0;
}
